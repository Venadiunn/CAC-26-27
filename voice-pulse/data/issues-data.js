const slugify = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const issueCatalog = categoryDefinitions.flatMap(({ name, items }) => {
  const baseSources = defaultSources[name] || [];
  return items.map((item, index) => {
    const categoryKey = name.toLowerCase().replace(/ & /g, '-').replace(/\s+/g, '-');
    const id = `${categoryKey}-${slugify(item.title)}`;
    const related = items
      .filter((_, i) => i !== index)
      .slice(0, 2)
      .map((entry) => `${categoryKey}-${slugify(entry.title)}`);

    return {
      id,
      title: item.title,
      category: name,
      summary: item.summary,
      subtopics: item.subtopics,
      keywords: item.keywords,
      governmentLevels: item.governmentLevels,
      affectedGroups: item.affectedGroups,
      policyQuestions: item.policyQuestions,
      sources: baseSources,
      relatedIssues: related,
      lastVerified: '2026-10-11',
    };
  });
});

const issueCategories = categoryDefinitions.map(({ name }) => name);

module.exports = {
  issueCategories,
  issueCatalog,
};
